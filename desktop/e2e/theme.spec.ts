import { expect, test } from '@playwright/test'

const lightThemes = [
  { id: 'light', family: '经典默认', accent: 'rgb(177, 42, 85)', surface2: 'rgb(243, 233, 238)' },
  { id: 'codex-light', family: '天空', accent: 'rgb(3, 105, 161)', surface2: 'rgb(241, 245, 249)' },
  { id: 'claude-light', family: '羊皮纸', accent: 'rgb(191, 81, 51)', surface2: 'rgb(243, 236, 225)' },
  { id: 'forest-light', family: '森林绿', accent: 'rgb(22, 101, 52)', surface2: 'rgb(230, 239, 231)' },
]

for (const theme of lightThemes) {
  test(`${theme.id} uses white surfaces while keeping themed actions, hover and selection`, async ({ page }) => {
    await page.goto('/e2e/conversation.html')
    await expect(page.getByRole('textbox')).toBeVisible()
    await page.evaluate(id => (window as any).conversationFixture.theme(id), theme.id)
    await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(page.locator('#root > div')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(page.locator('.misaka-atmosphere')).toHaveCSS('display', 'none')
    const toggle = page.getByRole('button', { name: '隐藏侧边栏', exact: true })
    await toggle.hover()
    await expect(toggle).toHaveCSS('background-color', theme.surface2)
    await page.getByRole('textbox').fill('主题配色验收')
    await expect(page.getByRole('button', { name: '发送指令 (Enter)', exact: true })).toHaveCSS('background-color', theme.accent)
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('button', { name: '外观与主题' }).click()
    const card = page.getByRole('button', { name: theme.family, exact: true })
    await card.click()
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme.id)
    await expect(card).toHaveAttribute('aria-pressed', 'true')
    await expect(card).toHaveCSS('border-color', theme.accent)
    await expect(card.locator(':scope > div').first()).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(page.getByRole('button', { name: '浅色主题', exact: true })).toHaveCSS('background-color', theme.accent)
  })

  test(`${theme.id} repaints the graph and minimap white without replacing research data`, async ({ page }) => {
    await page.goto('/e2e/conversation.html')
    await expect(page.getByRole('textbox')).toBeVisible()
    await page.evaluate(() => (window as any).conversationFixture.graph())
    await page.getByText('视图', { exact: true }).click()
    await expect(page.locator('.react-flow__node')).toHaveCount(2)
    await page.evaluate(id => (window as any).conversationFixture.theme(id), theme.id)
    await expect(page.locator('.react-flow')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(page.locator('.react-flow__minimap')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(page.locator('.react-flow__minimap-mask')).toHaveCSS('fill', 'rgba(255, 255, 255, 0.7)')
    await expect(page.locator('.react-flow__node')).toHaveCount(2)
  })
}

test('switching between light and dark modes hides and restores the existing atmosphere', async ({ page }) => {
  await page.goto('/e2e/conversation.html')
  await expect(page.getByRole('textbox')).toBeVisible()
  await expect(page.locator('.misaka-atmosphere')).toHaveCSS('display', 'none')
  await page.evaluate(() => (window as any).conversationFixture.theme('dark'))
  await expect(page.locator('.misaka-atmosphere')).toHaveCSS('display', 'block')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(24, 24, 30)')
  await page.evaluate(() => (window as any).conversationFixture.theme('forest-light'))
  await expect(page.locator('.misaka-atmosphere')).toHaveCSS('display', 'none')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
})

test('a registered developer palette updates real surfaces, states, menus and permissions together', async ({ page }) => {
  await page.goto('/e2e/conversation.html')
  const input = page.getByRole('textbox', { name: '给 Misaka 发送任务' })
  await expect(input).toBeVisible()
  await page.evaluate(() => (window as any).conversationFixture.theme('theme-probe'))
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'theme-probe')
  await expect(page.locator('html')).toHaveAttribute('data-theme-mode', 'light')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(6, 27, 40)')
  await expect(page.locator('.conversation-composer')).toHaveCSS('color', 'rgb(231, 255, 245)')
  const send = page.getByRole('button', { name: '发送指令 (Enter)' })
  await expect(send).toBeDisabled()
  await input.fill('主题颜色验证')
  await expect(send).toHaveCSS('background-color', 'rgb(67, 255, 225)')
  await expect(send).toHaveCSS('color', 'rgb(8, 46, 39)')
  await send.hover()
  await expect(send).toHaveCSS('color', 'rgb(8, 46, 39)')
  await input.focus()
  await expect(page.locator('.conversation-composer')).toHaveCSS('border-color', 'rgb(85, 255, 170)')
  await page.getByTitle('点击切换 Agent 模式').click()
  await expect(page.locator('.text-permission-plan')).toHaveCSS('color', 'rgb(0, 204, 255)')
  await expect(page.locator('.text-permission-edit')).toHaveCSS('color', 'rgb(0, 255, 136)')
  await expect(page.locator('.text-permission-bypass')).toHaveCSS('color', 'rgb(255, 102, 204)')
  await input.click({ position: { x: 500, y: 10 } })
  await page.evaluate(() => (window as any).conversationFixture.permission())
  await expect(page.getByText('操作审批请求', { exact: true })).toBeVisible()
  await expect(page.locator('.bg-overlay')).toHaveCSS('background-color', /^rgba\(18, 52, 86, 0\.5(?:02)?\)$/)
  await page.evaluate(() => (window as any).conversationFixture.theme('dark'))
  await expect(page.locator('.bg-overlay')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0.6)')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(24, 24, 30)')
})

test('appearance lists developer themes and keeps custom selection out of terminal configuration', async ({ page }) => {
  await page.goto('/e2e/conversation.html')
  await expect(page.getByRole('textbox')).toBeVisible()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '外观与主题' }).click()
  const probe = page.getByRole('button', { name: /开发主题验收/ })
  await expect(probe).toBeVisible()
  await probe.click()
  await expect(probe).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'theme-probe')
  expect(await page.evaluate(() => (window as any).conversationFixture.sent.filter((cmd: any) => cmd.type === 'set_theme'))).toEqual([])
  await page.getByRole('button', { name: /深色主题/ }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  expect(await page.evaluate(() => (window as any).conversationFixture.sent.filter((cmd: any) => cmd.type === 'set_theme').map((cmd: any) => cmd.name))).toEqual(['dark'])
})

test('markdown, tool output and errors consume their independent theme roles', async ({ page }) => {
  await page.goto('/e2e/conversation.html')
  await expect(page.getByRole('textbox')).toBeVisible()
  await page.evaluate(() => {
    const f = (window as any).conversationFixture
    f.theme('theme-probe')
    f.loadHistory([{ id: 'theme-message', role: 'assistant', timestamp: 1000, content: '# 标题\n\n[链接](https://example.com) 与 `代码`\n\n> 引文\n\n- 列表\n\n| 项 | 值 |\n|---|---|\n| A | B |', toolCalls: [{ id: 'theme-tool', name: 'read', status: 'error', result: '工具结果', error: '主题错误' }] }])
  })
  await expect(page.locator('.conversation-markdown h1')).toHaveCSS('color', 'rgb(255, 238, 136)')
  await expect(page.locator('.conversation-markdown a')).toHaveCSS('color', 'rgb(85, 221, 255)')
  await expect(page.locator('.conversation-inline-code')).toHaveCSS('color', 'rgb(255, 170, 221)')
  await expect(page.locator('.conversation-markdown blockquote')).toHaveCSS('color', 'rgb(170, 255, 221)')
  await page.getByRole('button', { name: /读取文件.*失败/ }).click()
  await expect(page.locator('.conversation-tool-error pre')).toHaveCSS('color', 'rgb(255, 119, 85)')
  await expect(page.locator('.conversation-tool-details pre').first()).toHaveCSS('color', 'rgb(153, 238, 255)')
})

test('open graph nodes, edges, controls and drawer repaint without replacing research data', async ({ page }) => {
  await page.goto('/e2e/conversation.html')
  await expect(page.getByRole('textbox')).toBeVisible()
  await page.evaluate(() => (window as any).conversationFixture.graph())
  await page.getByText('视图', { exact: true }).click()
  await expect(page.locator('.react-flow__node')).toHaveCount(2)
  await page.locator('.react-flow__node').first().click()
  await expect(page.getByRole('heading', { name: '根节点配色', level: 3 })).toBeVisible()
  await page.evaluate(() => (window as any).conversationFixture.theme('theme-probe'))
  await expect(page.locator('.react-flow')).toHaveCSS('background-color', 'rgb(4, 35, 46)')
  await expect(page.locator('.react-flow__edge-path').first()).toHaveCSS('stroke', 'rgb(224, 255, 85)')
  await expect(page.locator('.react-flow__controls-button').first()).toHaveCSS('background-color', 'rgb(17, 68, 85)')
  await expect(page.locator('.react-flow__controls-button').first()).toHaveCSS('color', 'rgb(187, 255, 238)')
  await expect(page.locator('.react-flow__minimap')).toHaveCSS('background-color', 'rgb(19, 61, 73)')
  await expect(page.locator('.react-flow__controls')).toHaveCSS('background-color', 'rgb(15, 52, 64)')
  await expect(page.locator('.react-flow__minimap-mask')).toHaveCSS('fill', /^rgba\(1, 35, 69, 0\.5(?:02)?\)$/)
  await expect(page.locator('.text-on-chart').last()).toHaveCSS('color', 'rgb(17, 34, 51)')
  await page.evaluate(() => (window as any).conversationFixture.theme('light'))
  await expect(page.locator('.react-flow__edge-path').first()).toHaveCSS('stroke', 'rgb(177, 42, 85)')
  await expect(page.locator('.text-on-chart').last()).toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(page.locator('.react-flow__node')).toHaveCount(2)
})
