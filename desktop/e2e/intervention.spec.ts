import { expect, test } from '@playwright/test'

test('intervention and follow-up preserve the running output, independent stop and unique echoes', async ({ page }) => {
  await page.goto('/e2e/conversation.html')
  const input = page.getByRole('textbox', { name: '给 Misaka 发送任务' })
  await expect(input).toBeVisible()
  await page.evaluate(() => (window as any).conversationFixture.replay(9))
  await input.fill('先验证源码')
  await input.press('Enter')
  await input.fill('稍后总结')
  await page.getByRole('button', { name: '发送选项' }).click()
  await page.getByRole('menuitem', { name: /后续排队/ }).click()
  const commands = await page.evaluate(() => (window as any).conversationFixture.sent.filter((c: any) => c.type === 'prompt'))
  expect(commands.map((c: any) => [c.text, c.streamingBehavior])).toEqual([['先验证源码', 'steer'], ['稍后总结', 'followUp']])
  await expect(page.getByRole('button', { name: '中止生成 (Esc)' })).toBeEnabled()
  await expect(page.getByText('读取请求已发出。')).toBeVisible()
  await page.evaluate(() => {
    const f = (window as any).conversationFixture
    f.emit({ type: 'message_start', message: { role: 'user', content: '先验证源码', timestamp: 1100 } })
    f.emit({ type: 'message_start', message: { role: 'user', content: '稍后总结', timestamp: 1200 } })
  })
  await expect(page.getByText('先验证源码', { exact: true })).toHaveCount(1)
  await expect(page.getByText('稍后总结', { exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: '中止生成 (Esc)' }).click()
  await expect(page.getByRole('button', { name: '停止中', exact: true })).toBeDisabled()
  await page.evaluate(() => (window as any).conversationFixture.emit({ type: 'agent_settled' }))
  await expect(page.getByRole('button', { name: '中止生成 (Esc)' })).toHaveCount(0)
})

test('failed queue submission retries in its original mode and menu Escape does not stop', async ({ page }) => {
  await page.goto('/e2e/conversation.html')
  const input = page.getByRole('textbox', { name: '给 Misaka 发送任务' })
  await expect(input).toBeVisible()
  await page.evaluate(() => {
    const f = (window as any).conversationFixture
    f.replay(9)
    f.failNextPrompt('测试提交失败')
  })
  await input.fill('稍后重新提交')
  await input.press('Alt+Enter')
  await expect(page.getByRole('status').filter({ hasText: '测试提交失败' })).toBeVisible()
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.getByText('稍后重新提交', { exact: true })).toHaveCount(1)
  expect(await page.evaluate(() => (window as any).conversationFixture.sent.filter((c: any) => c.type === 'prompt').map((c: any) => c.streamingBehavior))).toEqual(['followUp', 'followUp'])
  await input.fill('草稿')
  await page.getByRole('button', { name: '发送选项' }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).conversationFixture.sent.filter((c: any) => c.type === 'abort').length)).toBe(0)
  await page.setViewportSize({ width: 620, height: 900 })
  await page.getByRole('button', { name: '发送选项' }).click()
  await expect(page.getByRole('menu')).toBeVisible()
  expect(await page.locator('body').evaluate(e => e.scrollWidth - e.clientWidth)).toBeLessThanOrEqual(1)
  await page.screenshot({ path: 'test-results/intervention-menu.png', animations: 'disabled' })
})
