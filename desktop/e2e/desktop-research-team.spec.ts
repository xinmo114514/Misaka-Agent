import { expect, test } from '@playwright/test'
test.setTimeout(60000)

test.beforeEach(async ({ page }) => {
  await page.goto('/e2e/conversation.html')
  await expect(page.getByRole('textbox', { name: '给 Misaka 发送任务' })).toBeVisible()
  await page.evaluate(() => {
    const fixture = window as any
    fixture.conversationFixture.reset()
    fixture.modelPickerFixture.seed()
  })
  await expect(page.getByTitle('模型与思考深度')).toContainText('Misaka · 研究推理')
  await page.evaluate(() => (window as any).desktopResearchTeamFixture.seed())
  await page.getByTitle('点击切换 Agent 模式').click()
  await page.getByRole('button', { name: /研究模式/ }).click()
  const input = page.getByRole('textbox', { name: '给 Misaka 发送任务' })
  await input.fill('对照公开文献证据')
  await input.press('Enter')
  await expect(page.getByTestId('research-run-pill')).toBeVisible()
})

test('uses the effective team model, retains only selected roles, and surfaces conflicts', async ({ page }) => {
  await page.getByRole('button', { name: '展开研究过程' }).click()
  const team = page.getByTestId('desktop-research-team')
  await expect(team.getByText('证据核验员', { exact: true })).toBeVisible()
  await expect(team.getByText('misaka-fixture/full', { exact: true })).toHaveCount(2)
  await expect(team.getByText('old-pin/old-model')).toHaveCount(0)
  await page.evaluate(() => (window as any).conversationFixture.research.deliverFinalReport())
  const retain = team.getByRole('checkbox', { name: '保留 证据核验员' })
  await expect(retain).not.toBeChecked()
  await expect(team.getByRole('checkbox', { name: '保留 共享复核员' })).toBeDisabled()
  await expect(team.getByRole('button', { name: '确认保留所选角色' })).toBeDisabled()
  await retain.check()
  const name = team.getByRole('textbox', { name: '证据核验员 的保留名称' })
  await name.fill('共享复核员')
  await team.getByRole('button', { name: '确认保留所选角色' }).click()
  await expect(team.getByRole('alert')).toContainText('角色名称已存在')
  await name.fill('长期证据核验员')
  await team.getByRole('button', { name: '确认保留所选角色' }).click()
  await expect(team.getByText('已保留为 长期证据核验员')).toBeVisible()
  const commands = await page.evaluate(() => (window as any).conversationFixture.research.state().commands)
  const saves = commands.filter((command: any) => command.type === 'desktop_retain_roles')
  expect(saves.at(-1).selections).toEqual([{ id: 'evidence-expert', name: '长期证据核验员' }])
})

test('keeps committed model during pending switch, supports cancel and retry, and avoids ordinary writes', async ({ page }) => {
  await page.getByTitle('模型与思考深度').click()
  await expect(page.getByRole('slider')).toHaveAttribute('aria-disabled', 'true')
  await page.getByRole('button', { name: 'Misaka · 研究推理', exact: true }).click()
  await page.getByRole('button', { name: /两档推理模型.*2 档/ }).click()
  await expect(page.getByText('正在切换至 misaka-fixture/two')).toBeVisible()
  await expect(page.getByTitle('模型与思考深度')).toContainText('Misaka · 研究推理')
  await page.getByRole('button', { name: '取消模型切换' }).click()
  await expect(page.getByText('正在切换至 misaka-fixture/two')).toHaveCount(0)
  await page.getByRole('button', { name: 'Misaka · 研究推理', exact: true }).click()
  await page.getByRole('button', { name: /两档推理模型.*2 档/ }).click()
  await page.evaluate(() => (window as any).desktopResearchTeamFixture.failSwitch())
  await expect(page.getByRole('status')).toContainText('团队成员启动失败')
  await page.getByRole('button', { name: '重试模型切换' }).click()
  await page.evaluate(() => (window as any).desktopResearchTeamFixture.completeSwitch())
  await expect(page.getByTitle('模型与思考深度')).toContainText('两档推理模型')
  const ordinary = await page.evaluate(() => (window as any).conversationFixture.sent)
  expect(ordinary.filter((command: any) => ['set_model', 'set_default_model', 'set_setting'].includes(command.type))).toEqual([])
})
