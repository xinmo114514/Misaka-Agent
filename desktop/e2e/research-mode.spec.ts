import { expect, test } from '@playwright/test'
test.setTimeout(60000)

test.beforeEach(async ({ page }) => {
  await page.goto('/e2e/conversation.html')
  await expect(page.getByRole('textbox', { name: '给 Misaka 发送任务' })).toBeVisible()
  await page.evaluate(() => (window as any).conversationFixture.reset())
})

test('starts fully autonomous research from the Agent menu and existing composer', async ({ page }) => {
  await page.evaluate(() => (window as any).modelPickerFixture.seed())
  await page.getByTitle('点击切换 Agent 模式').click()
  await page.getByRole('button', { name: /研究模式/ }).click()
  await expect(page.getByTitle('点击切换 Agent 模式')).toContainText('研究模式')
  const input = page.getByRole('textbox', { name: '给 Misaka 发送任务' })
  await input.fill('比较 RAG 和长上下文的文献证据')
  await input.press('Enter')
  // A new run is configured first; this case studies the autonomous path, so it lifts the review.
  const wizard = page.getByRole('dialog', { name: '研究参数确认' })
  await expect(wizard).toBeVisible()
  await wizard.getByRole('checkbox', { name: '计划审批' }).uncheck()
  await wizard.getByRole('button', { name: '确认并开始研究' }).click()
  // 专注模式 reads as an ordinary chat; the run's state is announced by the header team pill.
  await expect(page.locator('[data-research-focus-view]')).toBeVisible()
  await expect(page.getByRole('button', { name: /研究团队/ })).toContainText('团队 · 6')
  await expect(page.locator('[data-research-focus-toolbar] .research-status')).toHaveAttribute('title', 'active')
  const run = await page.evaluate(() => (window as any).conversationFixture.research.state())
  expect(run.start).toMatchObject({ question: '比较 RAG 和长上下文的文献证据',
    workspace: 'C:/research', limits: { plan_approval: false } })
  expect(run.commands).toContainEqual(expect.objectContaining({ type: 'set_permission_mode', mode: 'bypassPermissions' }))
  // Research binds the picker to the run's team roles, not to the plain session model.
  expect(run.commands).toContainEqual(expect.objectContaining({ type: 'desktop_set_team_model', role: 'sister', provider: 'misaka-fixture', modelId: 'full' }))
  await page.screenshot({ path: 'test-results/research-mode-started.png' })
  await expect(page.getByTitle('点击切换 Agent 模式')).toContainText('研究模式')
  await expect(page.getByRole('textbox')).toHaveValue('')
  await page.getByTitle('点击切换 Agent 模式').click()
  await page.getByRole('button', { name: /标准模式/ }).click()
  await expect(page.getByTitle('点击切换 Agent 模式')).toContainText('标准模式')
  await page.getByRole('textbox').fill('普通聊天')
  await page.getByRole('textbox').press('Enter')
  const sent = await page.evaluate(() => (window as any).conversationFixture.sent)
  expect(sent).toContainEqual(expect.objectContaining({ type: 'prompt', text: '普通聊天' }))
})

test('research menu stays usable in the narrow welcome viewport', async ({ page }) => {
  await page.setViewportSize({ width: 760, height: 600 })
  await page.getByTitle('点击切换 Agent 模式').click()
  const menu = page.getByText('选择 Agent 模式').locator('..')
  const box = await menu.boundingBox()
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(760)
  await page.getByRole('button', { name: /研究模式/ }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results/research-mode-menu.png' })
  await page.getByRole('button', { name: /研究模式/ }).click()
  await expect(page.getByRole('button', { name: '开始研究 (Enter)' })).toBeDisabled()
})

test('keeps supplements, clarification answers and report followups in the same real research channel', async ({ page }) => {
  await page.getByTitle('点击切换 Agent 模式').click()
  await page.getByRole('button', { name: /研究模式/ }).click()
  const input = page.getByRole('textbox', { name: '给 Misaka 发送任务' })
  await input.fill('比较公开文献中的两种方法')
  await input.press('Enter')
  const wizard = page.getByRole('dialog', { name: '研究参数确认' })
  await expect(wizard).toBeVisible()
  await wizard.getByRole('checkbox', { name: '计划审批' }).uncheck()
  await wizard.getByRole('button', { name: '确认并开始研究' }).click()
  await expect(page.locator('[data-research-focus-view]')).toBeVisible()
  await expect(input).toHaveValue('')
  await input.fill('只看有出处的结论')
  await input.press('Enter')
  await expect(input).toHaveValue('')
  await expect(page.getByText('只看有出处的结论', { exact: true })).toHaveCount(1)
  await page.evaluate(() => (window as any).conversationFixture.research.clarify())
  await expect(page.getByText('是否只使用公开文献？')).toBeVisible()
  await input.fill('是的，只使用公开文献')
  await input.press('Enter')
  await expect(input).toHaveValue('')
  await expect(page.getByText('是的，只使用公开文献', { exact: true })).toHaveCount(1)
  await page.evaluate(() => (window as any).conversationFixture.research.deliverFinalReport())
  await expect(page.getByTestId('research-final-report')).toBeVisible()
  await input.fill('解释报告里的证据核验结论')
  await input.press('Enter')
  await expect(page.getByText('根据刚才的研究报告，检索方案更便于逐条核验证据。')).toBeVisible()
  const state = await page.evaluate(() => (window as any).conversationFixture.research.state())
  const inputs = state.commands.filter((command: any) => command.type === 'send_research_message')
  expect(inputs).toHaveLength(4)
  expect(inputs.slice(1).every((command: any) => command.runId === 'r_desktop_fixture')).toBe(true)
  // One run, one chat: the run entry is the focus bar, not a pill repeated in the transcript.
  await expect(page.locator('[data-research-focus-view]')).toHaveCount(1)
  await page.screenshot({ path: 'test-results/continuous-research.png' })
})
